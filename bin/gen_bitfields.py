#!/usr/bin/env python3
"""Write meshtastic/protobuf/bitfields.py from a descriptor set that carries source info.

Names every bit of every packed bitfield the schema declares, using the protobufs repo's
own discovery and naming (protobufs/tools/gen_bitfield_accessors.py), so a bit is called
here what the firmware accessors call it.

Usage:
    gen_bitfields.py <descriptor.binpb> <output.py>
"""

import os
import pprint
import sys

from google.protobuf import descriptor_pb2

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "protobufs", "tools"))
from gen_bitfield_accessors import accessor_name, collect_enums, find_bitfields, validate  # type: ignore  # pylint: disable=C0413

HEADER = '''"""Generated by bin/gen_bitfields.py from the protobufs submodule -- do not edit.

The named bits of every packed bitfield: {message: {bit name: (field, mask)}}, with the
message named by its path inside the package. Names match the firmware accessors.
"""

'''


def main() -> int:
    """Read the descriptor set, write the table."""
    fds = descriptor_pb2.FileDescriptorSet()
    with open(sys.argv[1], "rb") as fh:
        fds.ParseFromString(fh.read())
    table: dict = {}
    for rec in find_bitfields(fds, collect_enums(fds)):
        problems = validate(rec)
        if problems:
            sys.exit(f"{rec['where']}: {'; '.join(problems)}")
        message, field = rec["where"].split(": ", 1)[1].rsplit(".", 1)
        bits = table.setdefault(message, {})
        for name, mask in rec["values"]:
            if not mask:
                continue
            bit = accessor_name(name, rec["values"])
            if bit in bits:
                sys.exit(f"{message}: two bits are named {bit}")
            bits[bit] = (field, mask)
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as fh:
        fh.write(HEADER + "BITFIELDS = " + pprint.pformat(table, width=100) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
